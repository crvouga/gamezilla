/**
 * The alert rules Grafana evaluates, generated from the objective files, the
 * indicator catalog and the pipeline-health definitions, and written to
 * `alert-rules.generated.json` for OpenTofu to read. Nothing in that file is
 * written by hand: `bun run --filter @libs/observability-shared slo:generate`
 * rewrites it, and a test fails while it differs from this generator.
 *
 * An expression carries `__ENVIRONMENT__`, which OpenTofu replaces with the
 * environment it is applying, so one file serves every environment that
 * shares the metrics stack.
 */

import type { AlertBundle } from '@pkgs/openslo-shared/alert-policy';
import { alertedObjective } from '@pkgs/openslo-shared/alert-policy';
import { budgetSpent } from '@pkgs/openslo-shared/burn-rate';
import type {
  AlertCondition,
  AlertPolicy,
  OpenSloDoc,
  Slo,
} from '@pkgs/openslo-shared/model';
import { parseDuration } from '@pkgs/openslo-shared/window';
import { PIPELINE_ALERTS } from './pipeline-alerts';
import {
  investigationCommand,
  metricBackedSlos,
  RUNBOOK_URL,
  sloAlertBundle,
} from './slo-alerts';
import type { MetricIndicator } from './slo-indicators';
import { indicatorFor } from './slo-indicators';
import { burnExpression, numberText, windowQueries } from './slo-promql';

export const ENVIRONMENT_PLACEHOLDER = '__ENVIRONMENT__';

export type AlertRule = {
  /** Stable identity; becomes the rule's uid (with the environment). */
  readonly key: string;
  readonly name: string;
  readonly expr: string;
  /** How long the expression must hold before the alert fires. */
  readonly for: string;
  readonly severity: 'critical' | 'warning';
  readonly owner: string;
  /** The objective this defends, or empty for pipeline health. */
  readonly slo: string;
  readonly summary: string;
  readonly runbook_url: string;
  readonly investigate_command: string;
  /** For an objective: the share of its window's budget this burn spends. */
  readonly budget_spent: string;
  /** For an objective: the burn rate that fires it, in times too fast. */
  readonly burn_threshold: number;
};

export type AlertRuleGroup = {
  /** `fast` is evaluated every minute, `slow` every five. */
  readonly key: 'fast' | 'slow';
  readonly name: string;
  readonly interval_seconds: number;
  readonly rules: readonly AlertRule[];
};

export type AlertRuleArtifact = {
  readonly generated: string;
  readonly groups: readonly AlertRuleGroup[];
};

const GENERATED_NOTE =
  'Generated by libs/observability-shared/scripts/slo-generate.ts from the objective files, the indicator catalog and the pipeline alerts. Do not edit.';

/** Short enough to fit a Grafana uid (40 characters) beside an environment name. */
export function ruleKey(policyName: string): string {
  let hash = 0x811c9dc5;
  for (const char of policyName) {
    hash = Math.imul(hash ^ char.charCodeAt(0), 0x01000193) >>> 0;
  }
  return `slo-${hash.toString(16).padStart(8, '0')}`;
}

function percent(share: number): string {
  return `${String(Math.round(share * 1000) / 10)}%`;
}

function ruleFor(input: {
  readonly slo: Slo;
  readonly indicator: MetricIndicator;
  readonly policy: AlertPolicy;
  readonly conditions: readonly AlertCondition[];
}): AlertRule {
  const { slo, indicator, policy, conditions } = input;
  const objective = alertedObjective(slo);
  const [first] = conditions;
  if (first === undefined)
    throw new Error(`policy ${policy.name} has no conditions`);
  const burning = conditions.map((condition) => {
    const queries = windowQueries({
      indicator,
      window: condition.lookbackWindow,
      environment: ENVIRONMENT_PLACEHOLDER,
    });
    return `${burnExpression({ queries, target: objective.target })} >= ${numberText(condition.threshold)}`;
  });
  const longest = conditions.reduce((best, c) =>
    (parseDuration(c.lookbackWindow) ?? 0) >
    (parseDuration(best.lookbackWindow) ?? 0)
      ? c
      : best
  );
  const floor = windowQueries({
    indicator,
    window: longest.lookbackWindow,
    environment: ENVIRONMENT_PLACEHOLDER,
  }).total;
  const hours = (parseDuration(longest.lookbackWindow) ?? 0) / 3_600_000;
  const expr = `${burning.map((b) => `(${b})`).join(' and ')} and (${floor} >= ${numberText(indicator.minimumEventsPerHour * hours)})`;
  const page = first.severity === 'page';
  const spent = budgetSpent({
    factor: first.threshold,
    lookback: longest.lookbackWindow,
    window: slo.timeWindow.duration,
  });
  return {
    key: ruleKey(policy.name),
    name: `${slo.displayName ?? slo.name}: ${policy.name.slice(slo.name.length + 1)} (${first.severity})`,
    expr,
    for: holdFor(policy, page),
    severity: page ? 'critical' : 'warning',
    owner: indicator.owner,
    slo: slo.name,
    summary: `${policy.description ?? policy.name} At this rate the burn spends ${percent(spent)} of the ${slo.timeWindow.duration} error budget in ${longest.lookbackWindow}.`,
    runbook_url: RUNBOOK_URL,
    investigate_command: investigationCommand({
      indicator,
      lookback: longest.lookbackWindow,
    }),
    budget_spent: percent(spent),
    burn_threshold: first.threshold,
  };
}

/** How long a firing expression must keep holding: longer for slower, quieter alerts. */
function holdFor(policy: AlertPolicy, page: boolean): string {
  if (!page) return '15m';
  return isFast(policy) ? '2m' : '5m';
}

/** The fast burn is judged every minute; slower tiers look back hours or days. */
function isFast(policy: AlertPolicy): boolean {
  return policy.name.endsWith('-fast-burn');
}

export function generateAlertRules(
  docs: readonly OpenSloDoc[]
): AlertRuleArtifact {
  const bundle: AlertBundle = sloAlertBundle(docs);
  const fast: AlertRule[] = [...PIPELINE_ALERTS];
  const slow: AlertRule[] = [];
  for (const slo of metricBackedSlos(docs)) {
    const indicator = indicatorFor(slo.indicator);
    if (indicator === undefined || indicator.kind === 'health-job-history')
      continue;
    for (const policy of bundle.policies.filter((p) =>
      p.name.startsWith(`${slo.name}-`)
    )) {
      const conditions = policy.conditions.flatMap((name) =>
        bundle.conditions.filter((c) => c.name === name)
      );
      const rule = ruleFor({ slo, indicator, policy, conditions });
      (isFast(policy) ? fast : slow).push(rule);
    }
  }
  return {
    generated: GENERATED_NOTE,
    groups: [
      {
        key: 'fast',
        name: 'Business observability',
        interval_seconds: 60,
        rules: fast,
      },
      {
        key: 'slow',
        name: 'Objective slow burn and budget',
        interval_seconds: 300,
        rules: slow,
      },
    ],
  };
}

export function renderAlertRules(artifact: AlertRuleArtifact): string {
  return `${JSON.stringify(artifact, null, 2)}\n`;
}
