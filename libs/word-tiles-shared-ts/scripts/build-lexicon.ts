/**
 * Acquire and preprocess the production word list (ENABLE, public domain)
 * into the artifact the game ships. Acquisition happens here, never during
 * play: the source is fetched once, checked against its pinned checksum,
 * normalised deterministically and written as the front-coded module
 * `src/word-tiles-lexicon-enable-data.ts`. Run it only to reproduce or
 * replace the artifact; gameplay pins the identities it prints in
 * `src/word-tiles-lexicon-catalog.ts`.
 *
 *   bun libs/word-tiles-shared-ts/scripts/build-lexicon.ts [--check]
 */
import { fileURLToPath } from 'node:url';
import { createGlobalHttpClient } from '@pkgs/http-client-shared-ts/global';
import { createRepoTreeObjectStore } from '@pkgs/object-store-node-fs-server-ts/repo-tree-store';
import {
  canonicalText,
  canonicalWords,
  encodeFrontCoded,
  sha256Hex,
} from '../src/word-tiles-lexicon-codec';
import { ENABLE_SOURCE } from '../src/word-tiles-lexicon-source';

const DATA_KEY =
  'libs/word-tiles-shared-ts/src/word-tiles-lexicon-enable-data.ts';

function dataModule(artifact: string): string {
  return [
    '// Generated by libs/word-tiles-shared-ts/scripts/build-lexicon.ts from',
    `// ${ENABLE_SOURCE.url} (sha256 ${ENABLE_SOURCE.sha256}).`,
    '// The ENABLE word list is in the public domain. Do not edit by hand.',
    '/** The production word list, front-coded (see word-tiles-lexicon-codec). */',
    `export const ENABLE_WORDS =\n  '${artifact}';`,
    '',
  ].join('\n');
}

const http = createGlobalHttpClient();
const response = await http.fetch(ENABLE_SOURCE.url);
if (!response.ok) throw new Error(`download failed: ${response.status}`);
const source = await response.text();
const sourceSha = await sha256Hex(source);
if (sourceSha !== ENABLE_SOURCE.sha256)
  throw new Error(`source checksum ${sourceSha} is not the pinned one`);
const { words, refused } = canonicalWords(
  source
    .split('\n')
    .filter((line) => line.replace(/\r$/, '').length <= 15)
    .join('\n')
);
const artifact = encodeFrontCoded(words);
const identities = {
  words: words.length,
  refused: refused.length,
  listSha256: await sha256Hex(canonicalText(words)),
  artifactSha256: await sha256Hex(artifact),
};
const repo = createRepoTreeObjectStore({
  rootDir: fileURLToPath(new URL('../../..', import.meta.url)),
});
if (!process.argv.includes('--check'))
  await repo.put(
    DATA_KEY,
    new TextEncoder().encode(dataModule(artifact)),
    'text/typescript'
  );
process.stdout.write(`${JSON.stringify(identities, null, 2)}\n`);
