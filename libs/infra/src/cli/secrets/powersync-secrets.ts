export class PowerSyncUrl implements SecretEntry {
  readonly secretKey = 'POWERSYNC_URL';
  readonly env = 'POWERSYNC_URL';
  readonly optional = true;
  readonly hint =
    'PowerSync instance URL, e.g. https://<instance-id>.powersync.journeyapps.com';

  async validate(value: string): Promise<string | null> {
    const v = value.trim();
    if (v.length === 0) return 'Must be non-empty';
    try {
      const url = new URL(v);
      if (url.protocol !== 'https:') {
        return 'Must use https://';
      }
    } catch {
      return 'Must be a valid URL';
    }
    return null;
  }
}

