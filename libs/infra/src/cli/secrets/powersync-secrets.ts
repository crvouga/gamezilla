export class PowerSyncJwtPublicJwk implements SecretEntry {
  readonly secretKey = 'POWERSYNC_JWT_PUBLIC_JWK';
  readonly env = 'POWERSYNC_JWT_PUBLIC_JWK';
  readonly optional = true;
  readonly hint =
    'Inline RS256 public JWK JSON for PowerSync client_auth (generated by infra provision)';

  async validate(value: string): Promise<string | null> {
    const v = value.trim();
    if (v.length === 0) return 'Must be non-empty';
    try {
      const parsed: unknown = JSON.parse(v);
      if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
        return 'Must be a JSON object';
      }
      const kid = (parsed as Record<string, unknown>)['kid'];
      if (typeof kid !== 'string' || kid.length === 0) {
        return 'Must include a non-empty kid';
      }
    } catch {
      return 'Must be valid JSON';
    }
    return null;
  }
}
