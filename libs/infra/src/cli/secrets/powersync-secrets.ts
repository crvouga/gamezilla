import type { SecretEntry } from './types';

function requireNonEmpty(value: string): string | null {
  return value.trim().length === 0 ? 'Must be non-empty' : null;
}

export class PowerSyncInstanceId implements SecretEntry {
  readonly secretKey = 'POWERSYNC_INSTANCE_ID';
  readonly env = 'POWERSYNC_INSTANCE_ID';
  readonly optional = true;
  readonly hint =
    'PowerSync Cloud instance id (written to powersync/cli.yaml via !env)';

  async validate(value: string): Promise<string | null> {
    return requireNonEmpty(value);
  }
}

