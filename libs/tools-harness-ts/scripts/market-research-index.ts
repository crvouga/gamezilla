// @io-wall-ok — CLI entry for the market research index.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const research = new Bun.Glob('{apps,libs,pkgs}/*/docs/**/MARKET_RESEARCH.md');

function entry(path: string) {
  const firstLine = readFileSync(path, 'utf8').trimStart().split('\n', 1)[0];
  const title = firstLine
    ?.trimEnd()
    .match(/^# (.+)$/u)?.[1]
    ?.trim();
  if (!title) {
    throw new Error(`Start ${path} with a # title naming the product area.`);
  }
  return { path, title };
}

const entries = [...research.scanSync('.')].sort().map(entry);
entries.sort((a, b) => a.title.localeCompare(b.title, 'en'));
const links = entries.map(({ path, title }) => {
  const label = title
    .replaceAll('\\', '\\\\')
    .replaceAll('[', '\\[')
    .replaceAll(']', '\\]');
  return `- [${label}](../${path})`;
});
const content = [
  '# Market research by domain',
  '',
  'Generated by `bun run research:index`. [Maintain market research](../README.md#market-research).',
  '',
  ...(links.length
    ? links
    : ['No market research documents in this checkout yet.']),
  '',
].join('\n');

mkdirSync('docs', { recursive: true });
writeFileSync('docs/MARKET_RESEARCH_INDEX.md', content);
