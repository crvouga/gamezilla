// @io-wall-ok — composition root
/** Instruction discovery adapters; AGENTS.md remains the only rule source. */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = join(import.meta.dirname, '../../..');
const TARGETS = [
  {
    path: '.continue/rules/AGENTS.md',
    frontmatter:
      '---\nname: Repository instructions\nalwaysApply: true\n---\n\n',
  },
  { path: '.kiro/steering/AGENTS.md', frontmatter: '' },
  { path: 'GEMINI.md', frontmatter: '' },
  { path: '.github/copilot-instructions.md', frontmatter: '' },
  { path: '.clinerules/AGENTS.md', frontmatter: '' },
  {
    path: '.windsurf/rules/AGENTS.md',
    frontmatter: '---\ntrigger: always_on\n---\n\n',
  },
];

/** Writes discovery pointers, or reports drift without writing in check mode. */
export function syncAgentInstructions(verify: boolean): string[] {
  const drift: string[] = [];
  for (const target of TARGETS) {
    const abs = join(ROOT, target.path);
    const content = `${target.frontmatter}<!-- generated by bun run agents:sync — do not edit -->\n\nRead and follow the repository root AGENTS.md in full before working.\nAll project rules and verification requirements live there.\nShared commands live in .agents/commands/; read the requested command in full.\n`;
    const current = existsSync(abs) ? readFileSync(abs, 'utf8') : undefined;
    if (current === content) continue;
    drift.push(
      `${target.path} is ${current === undefined ? 'missing' : 'out of date'}`
    );
    if (verify) continue;
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }
  return drift;
}
