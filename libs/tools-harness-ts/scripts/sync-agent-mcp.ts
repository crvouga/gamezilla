/**
 * Agent MCP fan-out (part of `bun run agents:sync`, gate
 * `@libs/tools-harness-ts#ci:agent-commands`).
 *
 * Serena (`pipx:serena-agent` in `mise.toml`) gives agents symbol-level code
 * navigation and editing over MCP. Each coding agent reads its MCP servers
 * from its own project file and format, so this script writes the one Serena
 * entry into each, leaving every other entry in those files alone:
 *
 * - Claude Code: `.mcp.json`
 * - Codex: `.codex/config.toml` (a generated block; Codex loads it once the
 *   project is trusted)
 * - Cursor: `.cursor/mcp.json`
 * - Gemini CLI: `.gemini/settings.json`
 * - OpenCode: `opencode.json`
 * - VS Code and GitHub Copilot in VS Code: `.vscode/mcp.json`
 * - Factory / Droid: `.factory/mcp.json`
 * - Roo Code: `.roo/mcp.json`
 * - Kiro: `.kiro/settings/mcp.json`
 *
 * Windsurf and the Copilot CLI read only a per-user file, so no project file
 * can configure them; add the same `mise exec -- serena start-mcp-server`
 * command there by hand.
 *
 * Every entry launches Serena through `mise exec`, so the version pinned in
 * `mise.toml` runs even when the agent was started from a GUI whose `PATH`
 * has no mise shims. Agents that start in the project directory find the
 * project with `--project-from-cwd`; IDEs name it with `${workspaceFolder}`.
 * The dashboard never opens a browser tab: several agents run at once.
 *
 * Cursor also gets the hosted Sentry MCP server for the product's Sentry
 * organization (`external.sentryOrganization` in the product identity), so
 * that entry is generated too and follows the identity.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { PRODUCT } from '@libs/product-identity-shared-ts/product-identity';

const ROOT = join(import.meta.dirname, '../../..');
const SERVER = 'serena';
export const SYNC_COMMAND = 'bun run agents:sync';

const CODEX_BEGIN = `# BEGIN ${SERVER}: generated by \`${SYNC_COMMAND}\` — do not edit`;
const CODEX_END = `# END ${SERVER}`;

type Project = 'cwd' | 'workspace-folder';

interface Launch {
  /** Serena context for this client (`serena context list`). */
  context: string;
  project: Project;
}

/** The `mise` arguments that start the pinned Serena MCP server. */
export function serenaArgs({ context, project }: Launch): string[] {
  const where =
    project === 'cwd'
      ? ['--project-from-cwd']
      : ['--project', '${workspaceFolder}'];
  return [
    ...(project === 'cwd' ? [] : ['-C', '${workspaceFolder}']),
    'exec',
    '--',
    SERVER,
    'start-mcp-server',
    '--context',
    context,
    ...where,
    '--open-web-dashboard',
    'false',
  ];
}

interface JsonTarget {
  path: string;
  /** Object key that holds this client's MCP servers. */
  container: string;
  launch: Launch;
  entry: (args: string[]) => unknown;
  /** Keys written when the file is new or lacks them. */
  defaults?: Record<string, unknown>;
  /** Other generated servers, by name, written beside Serena. */
  servers?: Record<string, unknown>;
}

/** The hosted Sentry MCP server, scoped to the product's organization. */
export const SENTRY_MCP = {
  url: `https://mcp.sentry.dev/mcp/${PRODUCT.external.sentryOrganization}`,
};

const stdio = (args: string[]) => ({
  type: 'stdio',
  command: 'mise',
  args,
});

const JSON_TARGETS: JsonTarget[] = [
  ...[
    '.factory/mcp.json',
    '.roo/mcp.json',
    '.kiro/settings/mcp.json',
    '.continue/mcpServers/mcp.json',
  ].map((path) => ({
    path,
    container: 'mcpServers',
    launch: { context: 'ide', project: 'cwd' as const },
    entry: stdio,
  })),
  {
    path: '.mcp.json',
    container: 'mcpServers',
    launch: { context: 'claude-code', project: 'cwd' },
    entry: stdio,
  },
  {
    path: '.cursor/mcp.json',
    container: 'mcpServers',
    launch: { context: 'ide', project: 'workspace-folder' },
    entry: (args) => ({ command: 'mise', args }),
    servers: { Sentry: SENTRY_MCP },
  },
  {
    path: '.gemini/settings.json',
    container: 'mcpServers',
    launch: { context: 'ide', project: 'cwd' },
    entry: (args) => ({ command: 'mise', args }),
  },
  {
    path: '.vscode/mcp.json',
    container: 'servers',
    launch: { context: 'vscode', project: 'workspace-folder' },
    entry: stdio,
  },
  {
    path: 'opencode.json',
    container: 'mcp',
    launch: { context: 'ide', project: 'cwd' },
    entry: (args) => ({
      type: 'local',
      command: ['mise', ...args],
      enabled: true,
    }),
    defaults: { $schema: 'https://opencode.ai/config.json' },
  },
];

const CODEX_PATH = '.codex/config.toml';
const CODEX_LAUNCH: Launch = { context: 'codex', project: 'cwd' };

/** `existing` with the generated entries set; other keys are untouched. */
export function renderJson(
  existing: string | undefined,
  target: JsonTarget
): string {
  const doc = (existing === undefined ? {} : JSON.parse(existing)) as Record<
    string,
    unknown
  >;
  const servers = (doc[target.container] ?? {}) as Record<string, unknown>;
  const next = {
    ...target.defaults,
    ...doc,
    [target.container]: {
      ...servers,
      ...target.servers,
      [SERVER]: target.entry(serenaArgs(target.launch)),
    },
  };
  return `${JSON.stringify(next, null, 2)}\n`;
}

function codexBlock(): string {
  const args = serenaArgs(CODEX_LAUNCH)
    .map((arg) => JSON.stringify(arg))
    .join(', ');
  return [
    CODEX_BEGIN,
    `[mcp_servers.${SERVER}]`,
    // First start downloads the language server.
    'startup_timeout_sec = 60',
    'command = "mise"',
    `args = [${args}]`,
    CODEX_END,
    '',
  ].join('\n');
}

/** `existing` with the generated Serena block added or replaced. */
export function renderCodexToml(existing: string | undefined): string {
  const block = codexBlock();
  if (existing === undefined || existing.trim() === '') return block;
  const begin = existing.indexOf(CODEX_BEGIN);
  const end = existing.indexOf(CODEX_END);
  if (begin === -1 || end < begin)
    return `${existing.replace(/\n*$/, '\n\n')}${block}`;
  return `${existing.slice(0, begin)}${block}${existing
    .slice(end + CODEX_END.length)
    .replace(/^\n/, '')}`;
}

function read(path: string): string | undefined {
  const abs = join(ROOT, path);
  return existsSync(abs) ? readFileSync(abs, 'utf8') : undefined;
}

/**
 * Writes (or, with `verify`, only checks) every agent's Serena entry.
 * Returns one line per file that was missing or out of date.
 */
export function syncAgentMcp(verify: boolean): string[] {
  const wanted = [
    ...JSON_TARGETS.map((target) => ({
      path: target.path,
      render: (current: string | undefined) => renderJson(current, target),
    })),
    { path: CODEX_PATH, render: renderCodexToml },
  ];
  const drift: string[] = [];
  for (const { path, render } of wanted) {
    const current = read(path);
    const next = render(current);
    if (current === next) continue;
    drift.push(
      `${path} is ${current === undefined ? 'missing' : 'out of date'}`
    );
    if (verify) continue;
    mkdirSync(dirname(join(ROOT, path)), { recursive: true });
    writeFileSync(join(ROOT, path), next);
  }
  return drift;
}
