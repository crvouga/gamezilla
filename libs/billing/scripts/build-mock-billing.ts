// @io-wall-ok — generator script (composition root); writes the embedded mock billing SPA.
/**
 * Builds the mock provider's hosted pages and embeds the result in the server
 * bundle (`mock-billing-assets.generated.ts`), so every API host serves the
 * same files without a filesystem. `--check` rebuilds and compares, which is
 * how a stale bundle is caught (mirrors `@pkgs/idp-google-sim` `build:web`).
 *
 * `build({ write: false })` keeps the whole build in memory, so generating and
 * checking are the same code path.
 */

import path from 'node:path';
import { build } from 'vite';

const PACKAGE_DIR = path.join(import.meta.dir, '..');

/** Pin the production build so `--check` is identical under `bun test`. */
process.env['NODE_ENV'] = 'production';
const OUT = path.join(
  PACKAGE_DIR,
  'src/use-cases/mock-provider/server/mock-billing-assets.generated.ts'
);
const check = process.argv.includes('--check');

type ViteChunk = {
  readonly type: string;
  readonly fileName: string;
  readonly isEntry?: boolean;
  readonly code?: string;
  readonly source?: string | Uint8Array;
};

type ViteOutput = { readonly output?: readonly ViteChunk[] };

async function bundle(): Promise<{ js: string; css: string }> {
  const result = (await build({
    configFile: path.join(PACKAGE_DIR, 'vite-mock-billing.config.mts'),
    root: PACKAGE_DIR,
    build: { write: false },
  })) as unknown as ViteOutput;
  const output = result.output ?? [];
  const entry = output.find(
    (chunk) => chunk.type === 'chunk' && chunk.isEntry === true
  );
  const style = output.find(
    (chunk) => chunk.type === 'asset' && chunk.fileName.endsWith('.css')
  );
  if (entry?.code === undefined) {
    throw new Error('mock billing: the SPA build produced no entry chunk');
  }
  if (style?.source === undefined) {
    throw new Error('mock billing: the SPA build produced no stylesheet');
  }
  const css =
    typeof style.source === 'string'
      ? style.source
      : new TextDecoder().decode(style.source);
  return { js: entry.code, css };
}

function bytesOf(value: string): number {
  return new TextEncoder().encode(value).length;
}

function render(assets: { js: string; css: string }): string {
  return [
    '// GENERATED by scripts/build-mock-billing.ts — do not edit.',
    `// Embedded SPA bundle: JS ${String(bytesOf(assets.js))} bytes, ` +
      `CSS ${String(bytesOf(assets.css))} bytes.`,
    `export const MOCK_BILLING_SPA_JS = ${JSON.stringify(assets.js)};`,
    `export const MOCK_BILLING_SPA_CSS = ${JSON.stringify(assets.css)};`,
    '',
  ].join('\n');
}

const next = render(await bundle());

if (!check) {
  await Bun.write(OUT, next);
  console.warn(`wrote ${path.relative(process.cwd(), OUT)}`);
} else {
  const file = Bun.file(OUT);
  const current = (await file.exists()) ? await file.text() : '';
  if (current !== next) {
    console.error(
      'mock-billing-assets.generated.ts is stale — run `bun run --filter @libs/billing build:mock-billing`'
    );
    process.exit(1);
  }
  console.warn('mock-billing-assets.generated.ts up to date');
}
