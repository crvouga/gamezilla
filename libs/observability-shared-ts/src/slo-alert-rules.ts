export type AlertRuleGroup = {
  /** `fast` is evaluated every minute, `slow` every five. */
  readonly key: 'fast' | 'slow';
  readonly name: string;
  readonly interval_seconds: number;
  readonly rules: readonly AlertRule[];
};

export type AlertRuleArtifact = {
  readonly generated: string;
  readonly groups: readonly AlertRuleGroup[];
};

const GENERATED_NOTE =
  'Generated by libs/observability-shared-ts/scripts/slo-generate.ts from the objective files, the indicator catalog and the pipeline alerts. Do not edit.';

function longestOf(conditions: readonly AlertCondition[]): AlertCondition {
  const [first, ...rest] = conditions;
  if (first === undefined) throw new Error('a policy has no conditions');
  return rest.reduce(
    (best, c) =>
      (parseDuration(c.lookbackWindow) ?? 0) >
      (parseDuration(best.lookbackWindow) ?? 0)
        ? c
        : best,
    first
  );
}

function ruleFor(input: {
  readonly slo: Slo;
  readonly indicator: MetricIndicator;
  readonly policy: AlertPolicy;
  readonly conditions: readonly AlertCondition[];
}): AlertRule {
  const { slo, indicator, policy, conditions } = input;
  const objective = alertedObjective(slo);
  const longest = longestOf(conditions);
  // Judged slice by slice: one failing route group, check or probe burns on
  // its own and cannot hide inside a healthy total.
  const by = sliceLabel(indicator);
  const queriesOver = (window: string) =>
    windowQueries({
      indicator,
      window,
      environment: ENVIRONMENT_PLACEHOLDER,
      by,
    });
  const burning = conditions.map(
    (condition) =>
      `${burnExpression({ queries: queriesOver(condition.lookbackWindow), target: objective.target })} >= ${numberText(condition.threshold)}`
  );
  const floor = queriesOver(longest.lookbackWindow).total;
  const hours = (parseDuration(longest.lookbackWindow) ?? 0) / 3_600_000;
  const expr = `${burning.map((b) => `(${b})`).join(' and ')} and (${floor} >= ${numberText(indicator.minimumEventsPerHour * hours)})`;
  const severity = grafanaSeverity(longest.severity);
  const spent = budgetSpent({
    factor: longest.threshold,
    lookback: longest.lookbackWindow,
    window: slo.timeWindow.duration,
  });
  const lookback = exploreLookback(longest.lookbackWindow);
  return {
    key: ruleKey(policy.name),
    name: `${slo.displayName ?? slo.name}: ${policy.name.slice(slo.name.length + 1)} (${longest.severity})`,
    expr,
    for: holdFor(policy, severity, indicator),
    severity,
    owner: indicator.owner,
    slo: slo.name,
    tier: String(tierOf(slo)),
    route: routeOf(severity, tierOf(slo)),
    capability: slo.service,
    covers: '',
    slice_label: by ?? '',
    summary: `${policy.description ?? policy.name} At this rate the burn spends ${percent(spent)} of the ${slo.timeWindow.duration} error budget in ${longest.lookbackWindow}.`,
    runbook_url: runbookFor(slo.name),
    investigate_command: investigationCommand({
      indicator,
      lookback: longest.lookbackWindow,
    }),
    logs_path: logsPath(lookback),
    traces_path: tracesPath(lookback),
    budget_spent: percent(spent),
    burn_threshold: longest.threshold,
    budget_expr: budgetRemainingExpression({
      queries: queriesOver(slo.timeWindow.duration),
      target: objective.target,
    }),
  };
}

/** How long a firing expression must keep holding: longer for slower, quieter alerts. */
function holdFor(
  policy: AlertPolicy,
  severity: 'critical' | 'warning',
  indicator: MetricIndicator
): string {
  if (severity === 'warning') return '15m';
  return isFast(policy) ? (indicator.fastBurnHold ?? '2m') : '5m';
}

/** The fast burn is judged every minute; slower tiers look back hours or days. */
function isFast(policy: AlertPolicy): boolean {
  return policy.name.endsWith('-fast-burn');
}

export function generateAlertRules(
  docs: readonly OpenSloDoc[]
): AlertRuleArtifact {
  const bundle: AlertBundle = sloAlertBundle(docs);
  const fast: AlertRule[] = [
    ...PIPELINE_ALERTS,
    ...syncPerformanceAlerts(),
    ...certificateRules(),
    ...silenceRules(docs),
    ...lowTrafficRules(docs),
  ];
  const slow: AlertRule[] = [];
  for (const slo of metricBackedSlos(docs)) {
    const indicator = metricIndicatorOf(slo);
    // By label, not name: one objective's name can begin another's.
    for (const policy of bundle.policies.filter((p) =>
      p.labels['slo']?.includes(slo.name)
    )) {
      const conditions = policy.conditions.flatMap((name) =>
        bundle.conditions.filter((c) => c.name === name)
      );
      const rule = ruleFor({ slo, indicator, policy, conditions });
      (isFast(policy) ? fast : slow).push(rule);
    }
  }
  return {
    generated: GENERATED_NOTE,
    groups: [
      {
        key: 'fast',
        name: 'Business observability',
        interval_seconds: 60,
        rules: fast,
      },
      {
        key: 'slow',
        name: 'Objective slow burn and budget',
        interval_seconds: 300,
        rules: slow,
      },
    ],
  };
}

export function renderAlertRules(artifact: AlertRuleArtifact): string {
  return `${JSON.stringify(artifact, null, 2)}\n`;
}

/** Engineering target alerts. These never assert a measured population SLO. */
function rule(name: string, expr: string, critical: boolean): AlertRule {
  return {
    key: ruleKey(name),
    name,
    expr,
    for: '2m',
    severity: critical ? 'critical' : 'warning',
    owner: 'sync-engine',
    slo: '',
    tier: '0',
    route: critical ? 'page' : 'push',
    capability: 'sync-engine',
    covers: '',
    slice_label: '',
    summary:
      'Sync diagnostic target violation or missing evidence. Inspect environment, build and workload before inferring population performance.',
    runbook_url: `${README_URL.split('#')[0]}#sync-performance-targets`,
    investigate_command: 'bun obs slow --source prod --since 1h',
    logs_path: logsPath('1h'),
    traces_path: tracesPath('1h'),
    budget_spent: '',
    burn_threshold: 0,
    budget_expr: '',
  };
}

export function syncPerformanceAlerts(): readonly AlertRule[] {
  const series = emittedMetric(SYNC_TARGET_METRIC.name).series;
  if (series.kind !== 'counter')
    throw new Error('Sync target metric must be a counter');
  return SYNC_PERFORMANCE_TARGETS.flatMap((target) => {
    const cohort =
      target.stage === 'database' || target.stage === 'delivery'
        ? 'server'
        : 'foreground';
    const selector = `deployment_environment_name="__ENVIRONMENT__",app_sync_target="${target.id}",app_sync_cohort="${cohort}"`;
    const total = (window: string) =>
      `sum(increase(${series.total}{${selector},app_outcome!="unknown"}[${window}]))`;
    const bad = (window: string) =>
      `(sum(increase(${series.total}{${selector},app_outcome="bad"}[${window}])) or vector(0))`;
    const burn = (window: string) =>
      `(${bad(window)} / ${total(window)} / ${1 - target.share})`;
    const policies = STANDARD_BURN_TIERS.map((tier) =>
      rule(
        `sync-${target.id}-${tier.name}`,
        `(${burn(tier.longWindow)} >= ${tier.factor}) and (${burn(tier.shortWindow)} >= ${tier.factor}) and (${total(tier.shortWindow)} >= 20)`,
        tier.severity === 'page'
      )
    );
    return [
      ...policies,
      rule(
        `sync-${target.id}-uncertain-evidence`,
        `sum(increase(${series.total}{${selector},app_outcome="unknown"}[30m])) > 0`,
        false
      ),
      rule(
        `sync-${target.id}-low-traffic`,
        `${bad('30m')} >= 3 and ${total('30m')} < 20`,
        false
      ),
      rule(
        `sync-${target.id}-missing-evidence`,
        `absent_over_time(${series.total}{${selector}}[1d])`,
        false
      ),
    ];
  });
}
