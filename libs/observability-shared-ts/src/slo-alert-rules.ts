/**
 * The alert rules Grafana evaluates, generated from the objective files, the
 * indicator catalog and the pipeline-health definitions, and written to
 * `alert-rules.generated.json` for OpenTofu to read. Nothing in that file is
 * written by hand: `bun run libs/observability-shared-ts/scripts/slo-generate.ts`
 * rewrites it, and a test fails while it differs from this generator.
 *
 * An expression carries `__ENVIRONMENT__`, which OpenTofu replaces with the
 * environment it is applying, so one file serves every environment that
 * shares the metrics stack. Links are paths on the Grafana instance; OpenTofu
 * prefixes its URL and, for an objective, the address of its Grafana SLO.
 *
 * Three kinds of rule:
 *
 * - each objective's burn-rate policies (`slo` set), routed by tier and
 *   judged slice by slice (one alert per failing route group, check or
 *   probe);
 * - their companions (`companion-alerts`): silence, low-traffic counts and
 *   certificate expiry;
 * - the telemetry pipeline's own health (`pipeline-alerts`).
 */

