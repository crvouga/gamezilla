/**
 * The Grafana SLOs (the hosted SLO app's objectives, budgets and dashboards),
 * generated from the live objective files and the indicator catalog and
 * written to `grafana-slos.generated.json`, which OpenTofu turns into one
 * `grafana_slo` per entry and environment. Nothing in that file is written
 * by hand, and no `grafana_slo` exists without an objective file behind it:
 * a test fails on either.
 *
 * OpenSLO has no field for what only Grafana needs; the binding decides it
 * here, and `libs/observability-shared-ts/README.md` lists the mapping:
 *
 * | Grafana SLO          | from                                                    |
 * | -------------------- | ------------------------------------------------------- |
 * | name, description    | the SLO's `displayName` and `description`               |
 * | objective, window    | its one objective's target, its rolling `timeWindow`    |
 * | query                | the indicator's catalog entry, as a freeform ratio      |
 * | grouping             | the entry's `sliceBy` (`sum by`) in that ratio          |
 * | labels               | `tier`, the service, the SLO, the owner                 |
 * | alerting             | none: the generated burn-rate rules alert (see below)   |
 * | folder               | the environment's observability folder (OpenTofu)       |
 *
 * Grafana SLO's own alert rules cannot require a least amount of traffic or
 * a probe's cadence, so at today's volumes one failed request would page.
 * The rules in `alert-rules.generated.json` implement the same fast and slow
 * burn (critical and warning) from the same OpenSLO policies, with those
 * guards and the annotations a person needs.
 */

import { alertedObjective } from '@pkgs/openslo-shared-ts/alert-policy';
import type { OpenSloDoc } from '@pkgs/openslo-shared-ts/model';
import { parseDuration } from '@pkgs/openslo-shared-ts/window';
import { ENVIRONMENT_PLACEHOLDER } from './alert-links';
import {
  metricBackedSlos,
  metricIndicatorOf,
  TIER_LABEL,
  tierOf,
} from './slo-alerts';
import { sloRatioQuery } from './slo-promql';

/**
 * The longest window the metrics backend can answer: it keeps about 14
 * days, and Grafana SLO reads its whole window back.
 */
export const LONGEST_SLO_WINDOW = '14d';

export type GrafanaSlo = {
  /** The objective's `metadata.name`; the resource key in OpenTofu. */
  readonly key: string;
  readonly name: string;
  readonly description: string;
  /** Freeform ratio of good to all events, with `__ENVIRONMENT__`. */
  readonly query: string;
  readonly objective: number;
  /** A Prometheus duration (`7d`). */
  readonly window: string;
  readonly labels: Readonly<Record<string, string>>;
};

export type GrafanaSloArtifact = {
  readonly generated: string;
  readonly slos: readonly GrafanaSlo[];
};

const GENERATED_NOTE =
  'Generated by libs/observability-shared-ts/scripts/slo-generate.ts from the objective files and the indicator catalog. Do not edit.';

export function generateGrafanaSlos(
  docs: readonly OpenSloDoc[]
): GrafanaSloArtifact {
  return {
    generated: GENERATED_NOTE,
    slos: metricBackedSlos(docs).map((slo) => {
      const indicator = metricIndicatorOf(slo);
      const window = slo.timeWindow.duration;
      const longest = parseDuration(LONGEST_SLO_WINDOW) ?? 0;
      if (!slo.timeWindow.isRolling || (parseDuration(window) ?? 0) > longest) {
        throw new Error(
          `observability: SLO ${slo.name} needs a rolling window of at most ${LONGEST_SLO_WINDOW} (the metrics backend's retention), not ${window}`
        );
      }
      return {
        key: slo.name,
        name: slo.displayName ?? slo.name,
        description: (slo.description ?? '').replace(/\s+/g, ' ').trim(),
        query: sloRatioQuery({
          indicator,
          environment: ENVIRONMENT_PLACEHOLDER,
        }),
        objective: alertedObjective(slo).target,
        window,
        labels: {
          [TIER_LABEL]: String(tierOf(slo)),
          service: slo.service,
          slo: slo.name,
          owner: indicator.owner,
        },
      };
    }),
  };
}

export function renderGrafanaSlos(artifact: GrafanaSloArtifact): string {
  return `${JSON.stringify(artifact, null, 2)}\n`;
}
