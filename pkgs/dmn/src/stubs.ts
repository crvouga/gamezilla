/**
 * `bun test` discovers only `*.test.*` files, so the spec runner writes one
 * stub per DMN file into the package's `.cache/spec/` and passes those paths.
 * The stub imports the package's decisions entry (which registers the
 * bindings) and hands the file to the bun:test bridge. Nothing here is
 * committed.
 */

export type DmnStubInput = {
  readonly packageName: string;
  /** Absolute path of the `.dmn` file. */
  readonly specPath: string;
  /** Repo-relative uri used in reports (`specs/billing/access.dmn`). */
  readonly specUri: string;
  /** Absolute path of the package's decisions entry (`tests/decisions/index.ts`). */
  readonly entry: string;
  /** Absolute path of the bun:test bridge module (`@pkgs/dmn/bun-test`). */
  readonly bridge: string;
  /** Absolute path of the package's report bucket. */
  readonly reportDir: string;
};

/** `specs/billing/access.dmn` → `billing-access.dmn.test.ts`. */
export function dmnStubFileName(specUri: string): string {
  return `${specUri
    .replace(/^specs\//, '')
    .replace(/\.dmn$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')}.dmn.test.ts`;
}

export function dmnStubSource(input: DmnStubInput): string {
  const q = JSON.stringify;
  return [
    '// generated by the spec runner — do not edit, do not commit',
    `import ${q(input.entry)};`,
    `import { runDecisionSpec } from ${q(input.bridge)};`,
    '',
    `runDecisionSpec({ packageName: ${q(input.packageName)}, specPath: ${q(input.specPath)}, specUri: ${q(input.specUri)}, reportDir: ${q(input.reportDir)} });`,
    '',
  ].join('\n');
}
