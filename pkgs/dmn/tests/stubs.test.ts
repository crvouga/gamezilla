import { describe, expect, test } from 'bun:test';
import { bindDecisions, decisionBinding } from '@pkgs/dmn/registry';
import { dmnStubFileName, dmnStubSource } from '@pkgs/dmn/stubs';

describe('stubs', () => {
  test('one stub file per spec, named after its path', () => {
    expect(dmnStubFileName('specs/billing/access.dmn')).toBe(
      'billing-access.dmn.test.ts'
    );
    expect(dmnStubFileName('specs/chess/move-limits.dmn')).toBe(
      'chess-move-limits.dmn.test.ts'
    );
  });

  test('the stub imports the entry and hands the spec to the bridge', () => {
    expect(
      dmnStubSource({
        packageName: '@libs/billing',
        specPath: '/repo/specs/billing/access.dmn',
        specUri: 'specs/billing/access.dmn',
        entry: '/repo/libs/billing/tests/decisions/index.ts',
        bridge: '/repo/pkgs/dmn/src/bun-test.ts',
        reportDir: '/repo/libs/billing/.cache/report',
      })
    ).toBe(
      [
        '// generated by the spec runner — do not edit, do not commit',
        'import "/repo/libs/billing/tests/decisions/index.ts";',
        'import { runDecisionSpec } from "/repo/pkgs/dmn/src/bun-test.ts";',
        '',
        'runDecisionSpec({ packageName: "@libs/billing", specPath: "/repo/specs/billing/access.dmn", specUri: "specs/billing/access.dmn", reportDir: "/repo/libs/billing/.cache/report" });',
        '',
      ].join('\n')
    );
  });
});

describe('registry', () => {
  test('a spec binds once, and an unbound spec names the file to add', () => {
    const binding = {
      spec: 'registry-probe',
      layers: { app: { decide: () => ({}) } },
    };
    bindDecisions(binding);
    expect(decisionBinding('registry-probe')).toBe(binding);
    expect(() => bindDecisions(binding)).toThrow(
      'dmn: spec registry-probe is bound twice'
    );
    expect(() => decisionBinding('nowhere')).toThrow(
      "add tests/decisions/nowhere.binding.ts calling bindDecisions({ spec: 'nowhere'"
    );
  });
});
