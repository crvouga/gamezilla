/**
 * `bun test` discovers only `*.test.*` files, so the runner writes one stub
 * per feature into the package's `.cache/spec/` and passes those paths. The
 * stub imports the package's steps entry (which registers the world), reads
 * the feature, and hands it to the bun:test bridge. Nothing here is committed.
 */

export type StubInput = {
  readonly packageName: string;
  /** Absolute path of the feature file. */
  readonly featurePath: string;
  /** Package-relative uri used in reports (`features/remove-friend.feature`). */
  readonly featureUri: string;
  /** Absolute path of the steps entry module. */
  readonly stepsEntry: string;
  /** Absolute path of the bun:test bridge module (`@pkgs/gherkin/bun-test`). */
  readonly bridge: string;
};

export function stubFileName(featureUri: string): string {
  return `${featureUri
    .replace(/^features\//, '')
    .replace(/\.feature$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')}.feature.test.ts`;
}

export function stubSource(input: StubInput): string {
  const q = JSON.stringify;
  return [
    '// generated by the spec runner — do not edit, do not commit',
    `import ${q(input.stepsEntry)};`,
    `import { runFeature } from ${q(input.bridge)};`,
    '',
    `const source = await Bun.file(${q(input.featurePath)}).text();`,
    `runFeature(source, { packageName: ${q(input.packageName)}, featureUri: ${q(input.featureUri)} });`,
    '',
  ].join('\n');
}
