export type CuratedSound = {
  readonly id: string;
  readonly category: string;
  readonly relativePath: string;
  readonly sourceFile: string;
  readonly sourcePack: string;
  readonly sourceUrl: string;
  readonly volume: number;
  readonly tags: readonly string[];
  readonly intendedUsage: string;
};

const KENNEY = 'https://kenney.nl';

/** Resolve a source file relative to `.cache/kenney/staging/`. */
export function resolveStagingSource(relativePath: string): string {
  return path.join(
    import.meta.dir,
    '..',
    '.cache',
    'kenney',
    'staging',
    relativePath
  );
}

