// @io-wall-ok — composition-root wall FS via ObjectStore migration pending
import path from 'node:path';
import { wallClock } from '@pkgs/clock-shared-ts/wall';
import { createLogger } from '@pkgs/logger-shared-ts/logger';
import { CURATED_SOUNDS, KENNEY_ATTRIBUTION } from './curate-mapping';

const log = createLogger({
  name: 'sounds:generate-manifest',
  now: wallClock.now,
});

const ROOT = path.join(import.meta.dir, '..');
const ASSETS = path.join(ROOT, 'assets');
const MANIFEST_PATH = path.join(ROOT, 'src', 'manifest.json');
const URLS_PATH = path.join(ROOT, 'src', 'sound-urls.ts');
const VOLUMES_PATH = path.join(ROOT, 'src', 'sound-volumes.ts');
const SOUND_ID_PATH = path.join(ROOT, 'src', 'sound-id.ts');

type ManifestEntry = {
  id: string;
  category: string;
  filename: string;
  durationMs: number;
  tags: string[];
  volume: number;
  license: string;
  attribution: string;
  sourceUrl: string;
  sourceFile: string;
  intendedUsage: string;
  status: 'active';
};

async function probeDurationMs(filePath: string): Promise<number> {
  const proc = Bun.spawn(
    [
      'ffprobe',
      '-v',
      'error',
      '-show_entries',
      'format=duration',
      '-of',
      'default=noprint_wrappers=1:nokey=1',
      filePath,
    ],
    { stdout: 'pipe', stderr: 'pipe' }
  );
  const code = await proc.exited;
  if (code !== 0) {
    throw new Error(`ffprobe failed for ${filePath}`);
  }
  const text = (await new Response(proc.stdout).text()).trim();
  const seconds = Number.parseFloat(text);
  return Math.round(seconds * 1000);
}

function buildSoundsTree(): Record<string, Record<string, string>> {
  const tree: Record<string, Record<string, string>> = {};
  for (const sound of CURATED_SOUNDS) {
    const [category, name] = sound.id.split('.');
    if (!category || !name) {
      throw new Error(`Invalid sound id: ${sound.id}`);
    }
    tree[category] ??= {};
    tree[category][name] = sound.id;
  }
  return tree;
}

function formatSoundsTree(
  tree: Record<string, Record<string, string>>
): string {
  const lines: string[] = ['export const Sounds = {'];
  for (const category of Object.keys(tree).sort()) {
    lines.push(`  ${category}: {`);
    const entries = tree[category];
    if (!entries) continue;
    for (const name of Object.keys(entries).sort()) {
      lines.push(`    ${name}: '${entries[name]}',`);
    }
    lines.push('  },');
  }
  lines.push('} as const;');
  return lines.join('\n');
}

function formatSoundUrls(): string {
  const lines: string[] = [
    '// Generated by scripts/generate-manifest.ts — do not edit manually.',
    '// Vite / browser asset URLs.',
    'export const soundAssetUrls = {',
  ];
  for (const sound of CURATED_SOUNDS) {
    const assetPath = `../assets/${sound.relativePath}`;
    lines.push(
      `  '${sound.id}': new URL('${assetPath}', import.meta.url).href,`
    );
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type SoundAssetUrlId = keyof typeof soundAssetUrls;');
  return lines.join('\n');
}

/**
 * Playback volume is the only manifest field the shell reads at runtime, so it
 * ships as its own table: the full manifest (licenses, attributions, source
 * URLs) stays off the initial bundle.
 */
function formatSoundVolumes(): string {
  const lines: string[] = [
    '// Generated by scripts/generate-manifest.ts — do not edit manually.',
    '// Per-sound playback volume (`manifest.json` `volume`).',
    'const soundVolumes: Readonly<Record<string, number>> = {',
  ];
  for (const sound of CURATED_SOUNDS) {
    lines.push(`  '${sound.id}': ${String(sound.volume)},`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export function getManifestVolume(id: string): number {');
  lines.push('  return soundVolumes[id] ?? 1;');
  lines.push('}');
  return lines.join('\n');
}

function formatSoundIdFile(treeSource: string): string {
  return `// Generated by scripts/generate-manifest.ts — do not edit manually.

${treeSource}

type LeafValues<T> = T extends string
  ? T
  : T extends Record<string, infer U>
    ? LeafValues<U>
    : never;

export type SoundId = LeafValues<typeof Sounds>;

export function isSoundId(value: string): value is SoundId {
  return Object.values(Sounds).some((category) =>
    Object.values(category).includes(value as SoundId)
  );
}
`;
}

async function main(): Promise<void> {
  const manifest: ManifestEntry[] = [];
  for (const sound of CURATED_SOUNDS) {
    const assetPath = path.join(ASSETS, sound.relativePath);
    if (!(await Bun.file(assetPath).exists())) {
      throw new Error(`Missing curated asset: ${assetPath}`);
    }
    const durationMs = await probeDurationMs(assetPath);
    manifest.push({
      id: sound.id,
      category: sound.category,
      filename: sound.relativePath.replace(/^[^/]+\//, `${sound.category}/`),
      durationMs,
      tags: [...sound.tags],
      volume: sound.volume,
      license: 'CC0-1.0',
      attribution: KENNEY_ATTRIBUTION,
      sourceUrl: sound.sourceUrl,
      sourceFile: sound.sourceFile,
      intendedUsage: sound.intendedUsage,
      status: 'active',
    });
  }

  await Bun.write(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  await Bun.write(URLS_PATH, `${formatSoundUrls()}\n`);
  await Bun.write(VOLUMES_PATH, `${formatSoundVolumes()}\n`);

  const tree = buildSoundsTree();
  await Bun.write(SOUND_ID_PATH, formatSoundIdFile(formatSoundsTree(tree)));

  log.info(`Generated manifest (${manifest.length} sounds)`);
  log.info(`Wrote ${MANIFEST_PATH}`);
  log.info(`Wrote ${URLS_PATH}`);
  log.info(`Wrote ${VOLUMES_PATH}`);
  log.info(`Wrote ${SOUND_ID_PATH}`);
}

await main();
