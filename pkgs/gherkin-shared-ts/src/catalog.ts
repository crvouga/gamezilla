/**
 * Step catalogs: the wording a spec writer may use, per package, without
 * reading `tests/`. Generated; the check fails on drift.
 */

import type { ExtractedStep } from './extract';
import type { SpecFeature } from './parse';

export type CatalogPackage = {
  readonly name: string;
  readonly domains: readonly string[];
  readonly definitions: readonly ExtractedStep[];
  readonly imports: readonly string[];
  readonly features: readonly SpecFeature[];
  /** False when the package does not register the shared steps. */
  readonly sharedSteps?: boolean;
};

export const CATALOG_HEADER =
  '<!-- generated by `bun run spec:catalog` — do not edit; wording lives in tests/steps/** -->';

function parametersOf(text: string): string {
  const params = [...text.matchAll(/\{([^}]*)\}/g)].map(
    (m) => `{${m[1] ?? ''}}`
  );
  return params.length === 0 ? '—' : params.join(', ');
}

function cell(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
}

function usageCounts(features: readonly SpecFeature[]): Map<string, number> {
  const counts = new Map<string, number>();
  for (const feature of features) {
    for (const scenario of feature.scenarios) {
      for (const step of scenario.steps) {
        counts.set(step.text, (counts.get(step.text) ?? 0) + 1);
      }
    }
  }
  return counts;
}

/** Declared domains, then any feature directory the package also runs. */
function domainsRun(pkg: CatalogPackage): readonly string[] {
  const extra: string[] = [];
  for (const feature of pkg.features) {
    const domain = feature.uri.split('/')[1] ?? '';
    if (domain.length === 0) continue;
    if (pkg.domains.includes(domain) || extra.includes(domain)) continue;
    extra.push(domain);
  }
  return [...pkg.domains, ...extra];
}

function definitionRows(
  definitions: readonly ExtractedStep[],
  domain: string
): readonly string[] {
  return [...definitions]
    .sort(
      (a, b) =>
        (a.kind < b.kind ? -1 : a.kind > b.kind ? 1 : 0) ||
        (a.text < b.text ? -1 : a.text > b.text ? 1 : 0)
    )
    .map(
      (d) =>
        `| ${d.kind} | ${cell(d.text)} | ${cell(parametersOf(d.text))} | ${domain} |`
    );
}

/**
 * The package catalog: own steps, shared steps (when the package registers
 * them), imported steps, features.
 */
export function renderPackageCatalog(
  pkg: CatalogPackage,
  shared: readonly ExtractedStep[],
  imported: ReadonlyMap<string, readonly ExtractedStep[]>
): string {
  const table = (rows: readonly string[]) =>
    rows.length === 0
      ? '_none_'
      : [
          '| Kind | Step | Parameters | Domain |',
          '| --- | --- | --- | --- |',
          ...rows,
        ].join('\n');
  const domains = domainsRun(pkg);
  const counts = usageCounts(pkg.features);
  const scenarioCount = pkg.features.reduce(
    (n, f) => n + f.scenarios.length,
    0
  );
  const sections = [
    CATALOG_HEADER,
    `# Step catalog — ${pkg.name}`,
    '',
    `Tag every scenario with the \`@domain\` of its \`specs/<domain>/\` directory (${domains.map((d) => `\`@domain:${d}\``).join(', ')}). Features: ${String(pkg.features.length)}, scenarios: ${String(scenarioCount)}. Steps used here: ${String(counts.size)} distinct wordings.`,
    '',
    `## Steps of ${pkg.name}`,
    '',
    table(definitionRows(pkg.definitions, domains.join(', '))),
  ];
  if (pkg.sharedSteps !== false) {
    sections.push(
      '',
      '## Shared steps (every package that registers them)',
      '',
      table(definitionRows(shared, 'shared'))
    );
  }
  for (const [name, definitions] of imported) {
    sections.push(
      '',
      `## Steps imported from ${name}`,
      '',
      table(definitionRows(definitions, name.replace(/^.*\//, '')))
    );
  }
  sections.push('', '## Features', '');
  for (const feature of pkg.features) {
    sections.push(
      `- \`${feature.uri}\` — ${feature.name} (${String(feature.scenarios.length)} scenarios)`
    );
  }
  return `${sections.join('\n')}\n`;
}

/** Declared folders, plus `@synthetic` when the package also runs those features. */
function runsLabel(pkg: CatalogPackage): string {
  const folders = pkg.domains.map((domain) => `\`specs/${domain}/\``);
  const extra = domainsRun(pkg).some((domain) => !pkg.domains.includes(domain));
  return (extra ? [...folders, '`@synthetic`'] : folders).join(', ');
}

/** The root index: every package, the spec domains it runs, counts, and the catalog path. */
export function renderCatalogIndex<P extends CatalogPackage>(
  packages: readonly P[],
  catalogPathOf: (pkg: P) => string
): string {
  const rows = packages.map(
    (pkg) =>
      `| ${pkg.name} | ${runsLabel(pkg)} | ${String(pkg.features.length)} | ${String(pkg.features.reduce((n, f) => n + f.scenarios.length, 0))} | ${String(pkg.definitions.length)} | [catalog](${catalogPathOf(pkg)}) |`
  );
  return `${[
    CATALOG_HEADER,
    '# Step catalogs',
    '',
    "Features live in `specs/<domain>/<feature>.feature`. One catalog per package that runs spec domains (its `specDomains` against the harness, its `liveDomains` against a deployment). Spec writers read these and their context's `specs/<domain>/ubiquitous-language.yml`; they never read `src/` or `tests/`.",
    '',
    '| Package | Runs | Features | Scenarios | Own steps | Catalog |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
  ].join('\n')}\n`;
}
