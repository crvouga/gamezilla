/**
 * `bun test` discovers only `*.test.*` files, so the runner writes one stub
 * per feature into the package's `.cache/spec/` and passes those paths. The
 * stub imports the package's steps entry (which registers the world), reads
 * the feature, and hands it to the bun:test bridge. Nothing here is committed.
 */

export type StubInput = {
  readonly packageName: string;
  /** Absolute path of the feature file. */
  readonly featurePath: string;
  /** Repo-relative uri used in reports (`specs/friends/friend-remove.feature`). */
  readonly featureUri: string;
  /** Absolute path of the steps entry module. */
  readonly stepsEntry: string;
  /** Absolute path of the bun:test bridge module (`@pkgs/gherkin-server/bun-test`). */
  readonly bridge: string;
  /** Scenario names the host cannot run (`RunFeatureOptions.skip`). */
  readonly skip?: readonly string[] | undefined;
  /** One slice of the feature's scenarios (`RunFeatureOptions.slice`). */
  readonly slice?: StubSlice | undefined;
  /** Report bucket for behavior evidence (`RunFeatureOptions.reportDir`). */
  readonly reportDir?: string | undefined;
  /** Composition supplying reporting ports to the generated entry. */
  readonly reportBridge?: string | undefined;
  /** Layer a passing scenario proves (`RunFeatureOptions.layer`). */
  readonly layer?: 'system' | 'release' | undefined;
};

export type StubSlice = { readonly index: number; readonly count: number };

/** `-s<k>of<n>` for a slice, so every slice of a spec gets its own file. */
export function sliceSuffix(slice: StubSlice | undefined): string {
  return slice === undefined
    ? ''
    : `-s${String(slice.index)}of${String(slice.count)}`;
}

export function stubFileName(featureUri: string, slice?: StubSlice): string {
  return `${featureUri
    .replace(/^specs\//, '')
    .replace(/\.feature$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')}${sliceSuffix(slice)}.feature.test.ts`;
}

function sliceOption(slice: StubSlice | undefined): string {
  return slice === undefined ? '' : `, slice: ${JSON.stringify(slice)}`;
}

function evidenceOptions(input: StubInput): string {
  const q = JSON.stringify;
  return [
    input.reportDir === undefined ? '' : `, reportDir: ${q(input.reportDir)}`,
    input.reportDir === undefined || input.reportBridge === undefined
      ? ''
      : `, report: wallFeatureReport(${q(input.reportDir)})`,
    input.layer === undefined ? '' : `, layer: ${q(input.layer)}`,
  ].join('');
}

function skipOption(skip: readonly string[] | undefined): string {
  return skip === undefined || skip.length === 0
    ? ''
    : `, skip: ${JSON.stringify(skip)}`;
}

export function stubSource(input: StubInput): string {
  const q = JSON.stringify;
  return [
    '// generated by the spec runner — do not edit, do not commit',
    `import ${q(input.stepsEntry)};`,
    `import { runFeature } from ${q(input.bridge)};`,
    ...(input.reportBridge === undefined
      ? []
      : [`import { wallFeatureReport } from ${q(input.reportBridge)};`]),
    '',
    `const source = await Bun.file(${q(input.featurePath)}).text();`,
    `runFeature(source, { packageName: ${q(input.packageName)}, featureUri: ${q(input.featureUri)}${skipOption(input.skip)}${sliceOption(input.slice)}${evidenceOptions(input)} });`,
    '',
  ].join('\n');
}
