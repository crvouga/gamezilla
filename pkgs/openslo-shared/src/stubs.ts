/**
 * `bun test` discovers only `*.test.*` files, so the spec runner writes one
 * stub per objective file into the package's `.cache/spec/` and passes those
 * paths. The stub imports the package's openslo entry (which registers the
 * bindings) and hands the file to the bun:test bridge. Nothing here is
 * committed.
 */

export type SloStubInput = {
  readonly packageName: string;
  /** Absolute path of the `.openslo.yaml` file. */
  readonly specPath: string;
  /** Repo-relative uri used in reports (`specs/sync-engine/note-delivery.openslo.yaml`). */
  readonly specUri: string;
  /** Absolute path of the package's openslo entry (`tests/openslo/index.ts`). */
  readonly entry: string;
  /** Absolute path of the bun:test bridge module (`@pkgs/openslo-server/bun-test`). */
  readonly bridge: string;
  /** Absolute path of the package's report bucket. */
  readonly reportDir: string;
};

/** `specs/sync-engine/note-delivery.openslo.yaml` → `sync-engine-note-delivery.openslo.test.ts`. */
export function sloStubFileName(specUri: string): string {
  return `${specUri
    .replace(/^specs\//, '')
    .replace(/\.openslo\.ya?ml$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')}.openslo.test.ts`;
}

export function sloStubSource(input: SloStubInput): string {
  const q = JSON.stringify;
  return [
    '// generated by the spec runner — do not edit, do not commit',
    `import ${q(input.entry)};`,
    `import { runObjectiveSpec } from ${q(input.bridge)};`,
    '',
    `runObjectiveSpec({ packageName: ${q(input.packageName)}, specPath: ${q(input.specPath)}, specUri: ${q(input.specUri)}, reportDir: ${q(input.reportDir)} });`,
    '',
  ].join('\n');
}
