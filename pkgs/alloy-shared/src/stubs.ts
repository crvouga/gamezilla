/**
 * `bun test` discovers only `*.test.*` files, so the spec runner writes one
 * stub per structure spec into the package's `.cache/spec/`. The stub imports
 * the package's structure entry (which registers the bindings) and hands the
 * spec to the bun:test bridge. Nothing here is committed.
 */

export type AlloyStubInput = {
  readonly packageName: string;
  /** Absolute path of the `.als` model. */
  readonly specPath: string;
  /** Repo-relative uri used in reports (`specs/spaces/spaces.als`). */
  readonly specUri: string;
  /** Absolute path of the package's structure entry (`tests/structure/index.ts`). */
  readonly entry: string;
  /** Absolute path of the bun:test bridge module (`@pkgs/alloy/bun-test`). */
  readonly bridge: string;
  /** Absolute path of the package's report bucket. */
  readonly reportDir: string;
};

/** `specs/spaces/spaces.als` → `spaces-spaces.als.test.ts`. */
export function alloyStubFileName(specUri: string): string {
  return `${specUri
    .replace(/^specs\//, '')
    .replace(/\.als$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')}.als.test.ts`;
}

export function alloyStubSource(input: AlloyStubInput): string {
  const q = JSON.stringify;
  return [
    '// generated by the spec runner — do not edit, do not commit',
    `import ${q(input.entry)};`,
    `import { runStructureSpec } from ${q(input.bridge)};`,
    '',
    `runStructureSpec({ packageName: ${q(input.packageName)}, specPath: ${q(input.specPath)}, specUri: ${q(input.specUri)}, reportDir: ${q(input.reportDir)} });`,
    '',
  ].join('\n');
}
