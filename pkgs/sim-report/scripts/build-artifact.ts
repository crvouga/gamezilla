// @io-wall-ok — reads Vite dist and writes generated artifact module
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const distJs = join(root, 'dist', 'sim-report.js');
const distCss = join(root, 'dist', 'sim-report.css');
const outFile = join(root, 'src', 'generated', 'artifact.ts');

function escapeTemplate(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
}

const js = readFileSync(distJs, 'utf8');
let css = '';
try {
  css = readFileSync(distCss, 'utf8');
} catch {
  // Vite may omit CSS if empty; keep empty string.
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  [
    '// Generated by scripts/build-artifact.ts — do not edit',
    `export const ARTIFACT_JS = \`${escapeTemplate(js)}\`;`,
    `export const ARTIFACT_CSS = \`${escapeTemplate(css)}\`;`,
    '',
  ].join('\n'),
  'utf8'
);

console.log(`Wrote ${outFile} (js=${js.length} css=${css.length})`);
