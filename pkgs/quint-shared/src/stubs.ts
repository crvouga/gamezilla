/**
 * `bun test` discovers only `*.test.*` files, so the runner writes one stub
 * per model into the package's `.cache/spec/` and passes those paths. The
 * stub imports the package's quint entry (which registers the world and the
 * bindings) and hands the model to the bun:test bridge. Nothing here is
 * committed.
 */

export type ModelStubInput = {
  readonly packageName: string;
  /** Absolute path of the `.qnt` model. */
  readonly specPath: string;
  /** Repo-relative uri used in reports (`specs/spaces/space-hosting.qnt`). */
  readonly specUri: string;
  /** Absolute path of the package's quint entry (`tests/quint/index.ts`). */
  readonly quintEntry: string;
  /** Absolute path of the bun:test bridge module (`@pkgs/quint/bun-test`). */
  readonly bridge: string;
  /** Absolute path of the package's report bucket. */
  readonly reportDir: string;
  /** One slice of the model's traces (`RunModelOptions.slice`). */
  readonly slice?: ModelStubSlice | undefined;
};

export type ModelStubSlice = { readonly index: number; readonly count: number };

export function modelStubFileName(
  specUri: string,
  slice?: ModelStubSlice
): string {
  const suffix =
    slice === undefined
      ? ''
      : `-s${String(slice.index)}of${String(slice.count)}`;
  return `${specUri
    .replace(/^specs\//, '')
    .replace(/\.qnt$/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')}${suffix}.qnt.test.ts`;
}

export function modelStubSource(input: ModelStubInput): string {
  const q = JSON.stringify;
  return [
    '// generated by the spec runner — do not edit, do not commit',
    `import ${q(input.quintEntry)};`,
    `import { runQuintModel } from ${q(input.bridge)};`,
    '',
    `runQuintModel({ packageName: ${q(input.packageName)}, specPath: ${q(input.specPath)}, specUri: ${q(input.specUri)}, reportDir: ${q(input.reportDir)}${input.slice === undefined ? '' : `, slice: ${q(input.slice)}`} });`,
    '',
  ].join('\n');
}
