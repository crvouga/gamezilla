// @io-wall-ok — generator script (composition root); writes src/server/assets.generated.ts
/**
 * Builds the SPA and embeds the result in the server bundle.
 *
 * The provider has to serve its own screens from a Bun/SQLite process that has
 * no filesystem assumption, so the built JS and CSS are committed as strings
 * and served from `/idp-assets/*`. `--check` recomputes and compares, which is
 * how a stale bundle is caught in CI (mirrors `@pkgs/ui` `tokens:check`).
 *
 * `build({ write: false })` keeps the whole build in memory: nothing lands in
 * `dist/`, so generating and checking are the same code path.
 */

import path from 'node:path';
import { build } from 'vite';

const PACKAGE_DIR = path.join(import.meta.dir, '..');

/**
 * Vite's production build is what gets embedded. Pinning it keeps the bundle
 * (and therefore `--check`) identical no matter who runs it — `bun:test` sets
 * `NODE_ENV=test`, which would otherwise change the output.
 */
process.env['NODE_ENV'] = 'production';
const OUT = path.join(PACKAGE_DIR, 'src', 'server', 'assets.generated.ts');
const check = process.argv.includes('--check');

type ViteChunk = {
  readonly type: string;
  readonly fileName: string;
  readonly isEntry?: boolean;
  readonly code?: string;
  readonly source?: string | Uint8Array;
};

type ViteOutput = { readonly output?: readonly ViteChunk[] };

async function bundle(): Promise<{ js: string; css: string }> {
  const result = (await build({
    configFile: path.join(PACKAGE_DIR, 'vite.config.mts'),
    build: { write: false },
  })) as unknown as ViteOutput;
  const output = result.output ?? [];
  const entry = output.find(
    (chunk) => chunk.type === 'chunk' && chunk.isEntry === true
  );
  const style = output.find(
    (chunk) => chunk.type === 'asset' && chunk.fileName.endsWith('.css')
  );
  if (entry?.code === undefined) {
    throw new Error('idp: the SPA build produced no entry chunk');
  }
  if (style?.source === undefined) {
    throw new Error('idp: the SPA build produced no stylesheet');
  }
  const css =
    typeof style.source === 'string'
      ? style.source
      : new TextDecoder().decode(style.source);
  return { js: entry.code, css };
}

function bytesOf(value: string): number {
  return new TextEncoder().encode(value).length;
}

function render(assets: { js: string; css: string }): string {
  return [
    '// GENERATED by scripts/build-web-assets.ts — do not edit.',
    `// Embedded SPA bundle: JS ${String(bytesOf(assets.js))} bytes, ` +
      `CSS ${String(bytesOf(assets.css))} bytes.`,
    `export const IDP_SPA_JS = ${JSON.stringify(assets.js)};`,
    `export const IDP_SPA_CSS = ${JSON.stringify(assets.css)};`,
    '',
  ].join('\n');
}

const next = render(await bundle());

if (!check) {
  await Bun.write(OUT, next);
  console.warn(`wrote ${path.relative(process.cwd(), OUT)}`);
} else {
  const file = Bun.file(OUT);
  const current = (await file.exists()) ? await file.text() : '';
  if (current !== next) {
    console.error(
      'assets.generated.ts is stale — run `bun run --filter @pkgs/idp-google-sim build:web`'
    );
    process.exit(1);
  }
  console.warn('assets.generated.ts up to date');
}
