/**
 * The bridge end to end: a structure spec checked by Alloy, snapshots from
 * two adapters audited against it, the evidence it records — and the
 * registry and stubs the spec runner uses.
 */

import { describe, expect, test } from 'bun:test';
import { rmSync } from 'node:fs';
import { join } from 'node:path';
import { runStructureSpec } from '@pkgs/alloy-server/bun-test';
import { bindStructure, structureBinding } from '@pkgs/alloy-shared/registry';
import { alloyStubFileName, alloyStubSource } from '@pkgs/alloy-shared/stubs';
import type { Snapshot } from '@pkgs/alloy-shared/world';
import { readEvidence } from '@pkgs/conformance-server/evidence-store';

const SPEC_URI = 'pkgs/alloy-server/tests/fixtures/spaces.als';
const REPORT_DIR = join(import.meta.dir, '../.cache/test-report');
rmSync(REPORT_DIR, { recursive: true, force: true });

const space = (id: string, host: string, others: string[]): Snapshot => ({
  label: `space ${id}`,
  atoms: { Person: [host, ...others], Space: [id] },
  relations: {
    host: [[id, host]],
    members: [host, ...others].map((p) => [id, p]),
  },
});

bindStructure({
  spec: 'spaces',
  snapshots: {
    'server database': async () => [
      space('s1', 'alice', ['bob']),
      space('s2', 'carol', []),
    ],
    'device database': async () => [space('s1', 'alice', [])],
  },
});

runStructureSpec({
  packageName: '@pkgs/alloy',
  specPath: join(import.meta.dir, 'fixtures/spaces.als'),
  specUri: SPEC_URI,
  reportDir: REPORT_DIR,
});

describe('evidence', () => {
  test('every command and every adapter is recorded as a structure obligation', () => {
    const { records, malformed } = readEvidence(REPORT_DIR);
    expect(malformed).toEqual([]);
    const [record] = records;
    expect(record?.specUri).toBe(SPEC_URI);
    expect(record?.kind).toBe('structure');
    expect(
      record?.obligations.map((o) => [o.id, o.layer, o.status, o.detail])
    ).toEqual([
      [
        'command:HostIsAlwaysMember',
        'specification',
        'pass',
        'check HostIsAlwaysMember for 4: no counterexample within scope',
      ],
      [
        'command:SomeSpace',
        'specification',
        'pass',
        'run SomeSpace { some Space } for 3: instance found (expect 1)',
      ],
      ['snapshots:device database', 'implementation', 'pass', '1 snapshots'],
      ['snapshots:server database', 'implementation', 'pass', '2 snapshots'],
    ]);
  });
});

describe('registry', () => {
  test('a spec is bound once', () => {
    expect(() => bindStructure({ spec: 'spaces', snapshots: {} })).toThrow(
      'structure spec spaces is bound twice'
    );
  });

  test('a missing binding names the file to add', () => {
    expect(() => structureBinding('billing')).toThrow(
      "add bindStructure({ spec: 'billing', snapshots: { … } }) in tests/structure/billing.binding.ts and import it from tests/structure/index.ts"
    );
  });
});

describe('stubs', () => {
  test('one stub per spec, named after its path', () => {
    expect(alloyStubFileName('specs/spaces/spaces.als')).toBe(
      'spaces-spaces.als.test.ts'
    );
    expect(alloyStubFileName('specs/billing/seat-limits.als')).toBe(
      'billing-seat-limits.als.test.ts'
    );
  });

  test('the stub imports the entry and hands the spec to the bridge', () => {
    expect(
      alloyStubSource({
        packageName: '@apps/spaces',
        specPath: '/repo/specs/spaces/spaces.als',
        specUri: 'specs/spaces/spaces.als',
        entry: '/repo/apps/spaces/tests/structure/index.ts',
        bridge: '/repo/pkgs/alloy-server/src/bun-test.ts',
        reportDir: '/repo/apps/spaces/.cache/report',
      })
    ).toBe(
      [
        '// generated by the spec runner — do not edit, do not commit',
        'import "/repo/apps/spaces/tests/structure/index.ts";',
        'import { runStructureSpec } from "/repo/pkgs/alloy-server/src/bun-test.ts";',
        '',
        'runStructureSpec({ packageName: "@apps/spaces", specPath: "/repo/specs/spaces/spaces.als", specUri: "specs/spaces/spaces.als", reportDir: "/repo/apps/spaces/.cache/report" });',
        '',
      ].join('\n')
    );
  });
});
