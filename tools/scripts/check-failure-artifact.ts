/**
 * Writes / clears the agent-facing artifact produced by `bun check`.
 * Stable paths under repo-root `check/` (gitignored).
 */
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { buildLocalCheckFixPromptBody } from '../../libs/infra/src/cli/lib/build-llm-fix-prompt';

export const CHECK_FAILURE_ARTIFACT_DIR = 'check';
export const CHECK_LLM_FIX_PROMPT_REL = join(
  CHECK_FAILURE_ARTIFACT_DIR,
  'llm-fix-prompt.md'
);
export const CHECK_FAILURES_JSON_REL = join(
  CHECK_FAILURE_ARTIFACT_DIR,
  'failures.json'
);

export interface CheckStepFailure {
  readonly stepId: string;
  readonly bunScript: string;
  readonly exitCode: number;
  readonly output: string;
}

export interface CheckFailureArtifactPaths {
  readonly promptPath: string;
  readonly jsonPath: string;
}

async function tryUnlink(path: string): Promise<void> {
  try {
    await unlink(path);
  } catch (e) {
    const err = e as NodeJS.ErrnoException;
    if (err.code !== 'ENOENT') throw e;
  }
}

/** Remove stale agent artifacts after a green `bun check`. */
export async function clearCheckFailureArtifact(
  repoRoot: string
): Promise<void> {
  await Promise.all([
    tryUnlink(join(repoRoot, CHECK_LLM_FIX_PROMPT_REL)),
    tryUnlink(join(repoRoot, CHECK_FAILURES_JSON_REL)),
  ]);
}

/**
 * Write markdown prompt + JSON index for all failing lanes so an LLM agent
 * can fix everything in one go without re-scraping interleaved console logs.
 */
export async function writeCheckFailureArtifact(
  repoRoot: string,
  failures: ReadonlyArray<CheckStepFailure>
): Promise<CheckFailureArtifactPaths> {
  const dir = join(repoRoot, CHECK_FAILURE_ARTIFACT_DIR);
  await mkdir(dir, { recursive: true });

  const promptPath = join(repoRoot, CHECK_LLM_FIX_PROMPT_REL);
  const jsonPath = join(repoRoot, CHECK_FAILURES_JSON_REL);

  const prompt = buildLocalCheckFixPromptBody(
    failures.map((f) => ({ stepId: f.stepId, output: f.output }))
  );
  const header = [
    '<!-- Generated by `bun check`. Read this file and fix every failure below in one pass, then re-run `bun check`. -->',
    '',
  ].join('\n');

  const index = {
    generatedAt: new Date().toISOString(),
    command: 'bun check',
    instruction:
      'Read check/llm-fix-prompt.md and fix all listed failures in one pass, then re-run `bun check`.',
    promptPath: CHECK_LLM_FIX_PROMPT_REL,
    failedSteps: failures.map((f) => ({
      stepId: f.stepId,
      bunScript: f.bunScript,
      exitCode: f.exitCode,
    })),
  };

  await Promise.all([
    writeFile(promptPath, `${header}${prompt}\n`, 'utf8'),
    writeFile(jsonPath, `${JSON.stringify(index, null, 2)}\n`, 'utf8'),
  ]);

  return { promptPath, jsonPath };
}
